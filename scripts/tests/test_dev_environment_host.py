import errno
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import Mock, patch

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from dev_environment.host import Host
from dev_environment.model import StateStore, WorkflowError


class HostPortTest(unittest.TestCase):
    def inspect_with_socket(self, binding_error, connection_error):
        runner = Mock()
        runner.run.return_value = subprocess.CompletedProcess([], 0, '[main]\ndns=dnsmasq\n', '')
        with patch('dev_environment.host.shutil.which', return_value='/usr/bin/tool'), \
                patch('pathlib.Path.read_text', return_value='# Generated by NetworkManager'), \
                patch('dev_environment.host.socket.socket') as factory:
            listener = factory.return_value.__enter__.return_value
            listener.bind.side_effect = binding_error
            listener.connect_ex.return_value = connection_error
            return Host(None, runner).inspect()

    def test_docker_gateway_can_use_free_privileged_port_without_host_user_bind_permission(self):
        result = self.inspect_with_socket(PermissionError(errno.EACCES, 'privileged port'), errno.ECONNREFUSED)
        self.assertEqual(443, result['port'])

    def test_existing_listener_is_still_refused_when_user_cannot_bind(self):
        with self.assertRaisesRegex(WorkflowError, 'occupied'):
            self.inspect_with_socket(PermissionError(errno.EACCES, 'privileged port'), 0)

    def test_address_in_use_is_refused(self):
        with self.assertRaisesRegex(WorkflowError, 'occupied'):
            self.inspect_with_socket(OSError(errno.EADDRINUSE, 'address in use'), errno.ECONNREFUSED)


class HostSharedPathsTest(unittest.TestCase):
    @patch('pathlib.Path.is_file', return_value=True)
    def test_shared_paths_preserve_private_ca_and_limit_recursive_labels(self, _):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            store = StateStore(root / 'state')
            ca = store.root / 'host-setup/ca'
            ca.mkdir(parents=True)
            key = ca / 'rootCA-key.pem'
            key.write_text('private ca')
            source = root / 'checkout'
            source.mkdir()
            runner = Mock()
            Host(store, runner).share_paths([source])
            self.assertEqual('private ca', key.read_text())
            recursive = [Path(call.args[0][-1]) for call in runner.run.call_args_list if '-R' in call.args[0]]
            self.assertIn(source, recursive)
            self.assertIn(store.root / 'gateway', recursive)
            self.assertFalse(any(ca.is_relative_to(path) for path in recursive))

    def test_ca_or_its_parent_cannot_be_shared(self):
        with tempfile.TemporaryDirectory() as temporary:
            store = StateStore(Path(temporary) / 'state')
            ca = store.root / 'host-setup/ca'
            ca.mkdir(parents=True)
            runner = Mock()
            for path in (ca, store.root, Path(temporary)):
                with self.assertRaisesRegex(WorkflowError, 'private certificate authority'):
                    Host(store, runner).share_paths([path])
            runner.run.assert_not_called()


