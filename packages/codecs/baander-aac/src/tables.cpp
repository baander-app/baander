/* Window Functions */
void aac_sine_window(float* out, int n) {
  for (int i = 0; i < n; i++) {
    out[i] = (float)sin(M_PI * (i + 0.5) / n);
  }
}

static double bessel_i0(double x) {
  double sum = 1.0, term = 1.0;
  for (int k = 1; k < 64; k++) {
    term *= (x / (2.0 * k)) * (x / (2.0 * k));
    sum += term;
    if (term < sum * 1e-17) {
      break;
    }
  }
  return sum;
}

/* Kaiser-Bessel derived window of total length n (ISO/IEC 14496-3
 * 4.6.11.3.2): the Kaiser kernel has n/2 + 1 taps, and each half of the
 * window is the square root of its normalized running sum, so the window
 * satisfies the Princen-Bradley condition w[i]^2 + w[i + n/2]^2 = 1. */
void aac_kbd_window(float* out, int n, float alpha) {
  const int half = n / 2;
  double kernel[1025];
  double total = 0.0;
  for (int i = 0; i <= half; i++) {
    double r = 2.0 * i / half - 1.0;
    kernel[i] = bessel_i0(M_PI * alpha * sqrt(1.0 - r * r));
    total += kernel[i];
  }
  double sum = 0.0;
  for (int i = 0; i < half; i++) {
    sum += kernel[i];
    out[i] = (float)sqrt(sum / total);
    out[n - 1 - i] = out[i];
  }
}

