void aac_tables_init(void) {
  static bool done = false;
  if (done) {
    return;
  }
  for (int cb = 1; cb <= AAC_NUM_CODEBOOKS; cb++) {
    aac_huff_code[cb] = huff_code_ptrs[cb];
    aac_huff_len[cb] = huff_len_ptrs[cb];
  }
  /* Rising halves of the long and short windows of both frame lengths;
   * index 0 is sine, 1 KBD. */
  float full[2 * AAC_FRAME_SIZE_LONG];
  struct Window {
    float* out;
    int half;
    float alpha;
  };
  const Window windows[4] = {{aac_window_long[0], AAC_FRAME_SIZE_LONG, AAC_KBD_ALPHA_LONG},
                             {aac_window_short[0], AAC_FRAME_SIZE_SHORT, AAC_KBD_ALPHA_SHORT},
                             {aac_window_long_960[0], AAC_FRAME_SIZE_LONG_960, AAC_KBD_ALPHA_LONG},
                             {aac_window_short_120[0], AAC_FRAME_SIZE_SHORT_120, AAC_KBD_ALPHA_SHORT}};
  for (const Window& w : windows) {
    aac_sine_window(full, 2 * w.half);
    for (int i = 0; i < w.half; i++) {
      w.out[i] = full[i];
    }
    aac_kbd_window(full, 2 * w.half, w.alpha);
    for (int i = 0; i < w.half; i++) {
      w.out[w.half + i] = full[i];
    }
  }
  /* AAC-LD: sine and low-overlap rising halves.  The low-overlap window
   * of length n = 2 * half is 0 below 3n/16, a quarter sine period up to
   * 5n/16 and 1 above, so neighbouring windows overlap by n/8. */
  float* const ld_windows[2] = {aac_window_ld_512[0], aac_window_ld_480[0]};
  const int ld_halves[2] = {AAC_FRAME_SIZE_LD, AAC_FRAME_SIZE_LD_480};
  for (int t = 0; t < 2; t++) {
    const int half = ld_halves[t];
    const int n = 2 * half;
    float* sine = ld_windows[t];
    float* low = ld_windows[t] + half;
    aac_sine_window(full, n);
    for (int i = 0; i < half; i++) {
      sine[i] = full[i];
      if (i < 3 * n / 16) {
        low[i] = 0.0f;
      } else if (i < 5 * n / 16) {
        low[i] = (float)sin(M_PI / (n / 4.0) * (i - 3 * n / 16 + 0.5));
      } else {
        low[i] = 1.0f;
      }
    }
  }
  for (int i = 0; i < AAC_POW43_SIZE; i++) {
    aac_pow43[i] = (float)pow((double)i, 4.0 / 3.0);
  }
  done = true;
}

