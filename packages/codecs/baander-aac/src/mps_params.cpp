/* MPEG Surround parameter coding (ISO/IEC 23003-1 EcData(), shared with
 * the 2-1-2 tool of ISO/IEC 23003-3): the PCM, differential Huffman and
 * pair-wise Huffman coding of the CLD, ICC, IPD and CPC parameters, the
 * pilot-based coding of the AAC form, the band grouping of
 * bsFreqResStride, and the CPC quantiser.
 *
 *   EcDataPair(): bsPcmCoding (1); with it, when more than four bands
 *   are coded and the stream is MPEG Surround in AAC, bsPilotCoding (1).
 *   PCM packs groups of values into fixed-width words.  Huffman coding
 *   codes the differences in frequency or time (bsDiffType per set, not
 *   sent with pilot coding, where every value is a difference to the
 *   pilot value coded first), either one value at a time (magnitude and
 *   sign) or as pairs (bsCodingScheme): pairs along frequency or between
 *   the two sets (bsPairing), each with a LAV class, the pair codebook,
 *   the symmetry bits and an escape to PCM.  The fine IPD and CPC
 *   quantisers carry their lowest bit apart after the codes.
 *
 * The CPC codebooks and the quantiser tables are ISO/IEC 23003-1 data
 * transcribed from libxaac (Apache-2.0, Ittiam Systems / AOSP:
 * decoder/ixheaacd_mps_rom.c) and verified against it entry by entry
 * with a generated comparison; the CLD, ICC and IPD books live in
 * mps212_tables.cpp.  Node tables: an entry greater than zero is the
 * index of the next node, an entry of zero or less a leaf holding
 * -(symbol + 1); the two-dimensional books use the leaf value 0 as the
 * escape to PCM coding.  The books come per difference direction
 * (frequency, time, pilot) and, for the pairs, per pairing and LAV
 * class.  The pilot value of a set uses the first-value book of its
 * type. */
