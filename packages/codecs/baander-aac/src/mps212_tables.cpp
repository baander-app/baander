/* Tables of the MPEG Surround 212 decoder (ISO/IEC 23003-3 7.11 and the
 * one-to-two box of ISO/IEC 23003-1): the parameter band partitions, the
 * quantiser values, the Huffman codebooks of the parameter coding, the
 * hybrid filterbank prototypes, the decorrelator filters and the
 * temporal shaping constants.
 *
 * The data is ISO/IEC 23003-3 / 23003-1 data transcribed from libxaac
 * (Apache-2.0, Ittiam Systems / AOSP: decoder/ixheaacd_mps_rom.c,
 * ixheaacd_mps_parse.c, ixheaacd_mps_decorr.c,
 * ixheaacd_mps_temp_process.c) and verified against it entry by entry
 * with a generated comparison over the linked libxaac objects.
 *
 * Huffman codebooks: a node table holds a binary tree; an entry greater
 * than zero is the index of the next node, an entry of zero or less is
 * a leaf holding -(symbol + 1).  The two-dimensional books use the leaf
 * value 0 (symbol -1) as the escape to PCM coding.  The codebooks of a
 * parameter come per difference direction (frequency, time, and the
 * pilot variant that MPEG Surround keeps for its own use) and, for the
 * two-dimensional books, per pairing (frequency pair, time pair) and LAV
 * class. */
