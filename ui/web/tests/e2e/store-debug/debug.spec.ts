import { test, expect } from '@playwright/test'

test('disabled stores isolate renders; enabled UI traces, exports and disables recording', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByTestId('selection')).toHaveText('none')
  await page.getByRole('button', { name: 'Change view', exact: true }).click()
  await expect(page.getByTestId('selection-renders')).toHaveText('1')
  await page.getByRole('button', { name: 'Select album', exact: true }).click()
  await expect(page.getByTestId('selection')).toHaveText('album-one')
  await expect(page.getByTestId('action-renders')).toHaveText('1')
  await page.getByRole('button', { name: 'Select album', exact: true }).click()
  await expect(page.getByTestId('selection-renders')).toHaveText('2')
  await page.getByRole('button', { name: 'Toggle debug panel' }).click()
  await page.getByRole('button', { name: 'Store Timeline', exact: true }).click()
  await expect(page.getByText(/Store recording is disabled/)).toBeVisible()
  await page.getByRole('button', { name: 'Enable store tracing and reload' }).click()
  await expect(page.getByTestId('selection')).toHaveText('none')
  await page.getByRole('button', { name: 'Select album', exact: true }).click()
  await page.getByRole('button', { name: 'Toggle debug panel' }).click()
  await page.getByRole('button', { name: 'Store Timeline', exact: true }).click()
  const action = page.locator('summary').filter({ hasText: /select · action/ })
  await expect(action).toBeVisible()
  await action.click()
  await expect(action.locator('..').getByText('Call stack', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Export trace', exact: true }).click()
  const trace = JSON.parse(await page.getByRole('textbox', { name: 'Trace JSON' }).inputValue())
  expect(trace.schemaVersion).toBe(2)
  expect(trace.baseline).toEqual({ epoch: 1, boundaryEventId: null, stores: {} })
  expect(trace.events.some((event: { kind: string; instanceId: number }) => event.kind === 'register' && event.instanceId > 0)).toBe(true)
  expect(trace.events.some((event: { kind: string; changedKeys?: string[] }) => event.kind === 'update' && event.changedKeys?.includes('selectedId'))).toBe(true)
  const selectedUpdate = trace.events.find((event: { id: number; store: string; kind: string }) => event.store === 'catalog.selection' && event.kind === 'update')
  expect(selectedUpdate).toBeDefined()
  await page.getByRole('textbox', { name: 'Filter store actions' }).fill('catalog.selection')
  await page.getByRole('button', { name: `Inspect event #${selectedUpdate.id}`, exact: true }).click()
  const inspection = page.getByRole('region', { name: 'Captured state' })
  await expect(inspection).toContainText('"selectedId": "album-one"')
  await expect(inspection).toContainText('"selectedId": null')
  const history = page.getByRole('region', { name: 'Historical store captures' })
  await expect(history).toContainText('"selectedId": "album-one"')
  await expect(history).toContainText('"viewMode": "list"')
  await page.getByRole('button', { name: 'Select another album', exact: true }).click()
  await page.getByRole('button', { name: 'Change view', exact: true }).click()
  await expect(page.getByTestId('selection')).toHaveText('album-two')
  await expect(page.getByTestId('view-mode')).toHaveText('grid')
  await expect(history).toContainText('"viewMode": "list"')
  await expect(history).not.toContainText('"viewMode": "grid"')
  await expect(history).not.toContainText('album-two')
  await expect(inspection).toContainText(`#${selectedUpdate.id} catalog.selection`)
  await expect(inspection).not.toContainText('album-two')
  await page.getByRole('button', { name: 'Export trace', exact: true }).click()
  const eventsBeforeNavigation = JSON.parse(await page.getByRole('textbox', { name: 'Trace JSON' }).inputValue()).events
  await page.getByRole('button', { name: 'Next event', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(inspection).toContainText('This event has no state capture.')
  await page.getByRole('button', { name: 'Previous event', exact: true }).click()
  await expect(inspection).toContainText('"selectedId": "album-one"')
  await page.getByRole('button', { name: 'Export trace', exact: true }).click()
  expect(JSON.parse(await page.getByRole('textbox', { name: 'Trace JSON' }).inputValue()).events).toEqual(eventsBeforeNavigation)
  await expect(page.getByTestId('selection')).toHaveText('album-two')
  await expect(page.getByTestId('view-mode')).toHaveText('grid')
  await page.getByRole('button', { name: 'Clear timeline', exact: true }).click()
  await expect(inspection).toContainText('Select an event to inspect its captured state.')
  await page.getByRole('button', { name: 'Store Inspector', exact: true }).click()
  await page.getByRole('combobox', { name: 'Select store' }).click()
  await page.getByRole('option', { name: /selection/i }).click()
  await expect(page.getByText(/"selectedId": "album-two"/)).toBeVisible()
  await page.getByRole('button', { name: 'Disable store tracing and reload' }).click()
  await page.getByRole('button', { name: 'Toggle debug panel' }).click()
  await page.getByRole('button', { name: 'Store Timeline', exact: true }).click()
  await expect(page.getByText(/Store recording is disabled/)).toBeVisible()
})
