/** WCAG relative luminance contrast for opaque sRGB colors. */
export function contrast(first, second) {
  const luminance = hex => {
    const channels = hex.match(/[a-f\d]{2}/gi).map(value => {
      const channel = parseInt(value, 16) / 255;
      return channel <= 0.04045 ? channel / 12.92 : ((channel + 0.055) / 1.055) ** 2.4;
    });
    return channels[0] * 0.2126 + channels[1] * 0.7152 + channels[2] * 0.0722;
  };
  const values = [luminance(first), luminance(second)].sort((a, b) => b - a);
  return (values[0] + 0.05) / (values[1] + 0.05);
}

function mix(first, second, amount) {
  const channels = color => color.match(/[a-f\d]{2}/gi).map(value => parseInt(value, 16));
  const end = channels(second);
  return '#' + channels(first).map((value, i) =>
    Math.round(value + (end[i] - value) * amount).toString(16).padStart(2, '0')
  ).join('');
}

function readable(color, surfaces, ratio, dark) {
  const target = dark ? '#ffffff' : '#000000';
  for (let step = 0; step <= 1000; step++) {
    const candidate = mix(color, target, step / 1000);
    if (surfaces.every(surface => contrast(candidate, surface) >= ratio)) return candidate;
  }
  throw new Error(`Cannot resolve ${color} at ${ratio}:1 against ${surfaces.join(', ')}`);
}

const values = tokens => Object.fromEntries(Object.entries(tokens).map(([key, token]) => [key, token.value]));
const cssName = name => name.replace(/([a-z])([A-Z])/g, '$1-$2').replace(/([a-z])(\d)/g, '$1-$2').toLowerCase();
const namespaces = { colors: 'color', radii: 'radius', spacing: 'space', typography: 'font', durations: 'duration' };

function declarations(theme, groups = Object.keys(namespaces)) {
  return groups.flatMap(group => Object.entries(theme[group]).map(([key, value]) =>
    `  --${namespaces[group]}-${cssName(key)}: ${value};`
  ));
}

export function generateWeb(base, moods, palette, semantics) {
  const moodNames = Object.keys(semantics.moods);
  const accentPalette = values(palette.accent);
  const accents = Object.keys(accentPalette);
  const staticTokens = {
    radii: values(base.radius),
    spacing: values(base.space),
    typography: values(base.font),
    durations: values(base.duration),
  };
  const themes = {};
  for (const mood of moodNames) {
    const dark = mood === 'dark';
    themes[mood] = {};
    for (const accent of accents) {
      const colors = { ...values(base.color), ...values(moods[mood].color) };
      const surfaces = [colors.background, colors.card, colors.popover, colors.sidebar,
        colors.secondary, colors.muted, colors.highlight];
      const identity = accentPalette[accent];
      const textColor = color => readable(color, surfaces, semantics.normalTextContrast, dark);
      const actionColor = color => readable(color, surfaces, semantics.actionContrast, dark);
      const stateTarget = dark ? '#ffffff' : '#000000';
      colors.primary = actionColor(identity);
      colors.primaryForeground = dark ? '#000000' : '#ffffff';
      colors.primaryHover = mix(colors.primary, stateTarget, semantics.hoverMix);
      colors.primaryPressed = mix(colors.primary, stateTarget, semantics.pressedMix);
      colors.accentText = textColor(identity);
      colors.ring = readable(identity, surfaces, semantics.indicatorContrast, dark);
      colors.inputBoundary = readable(colors.input, surfaces, semantics.indicatorContrast, dark);
      colors.input = colors.inputBoundary;
      colors.mutedForeground = textColor(colors.mutedForeground);
      for (const [status, color] of Object.entries(semantics.status)) {
        colors[status] = actionColor(color);
        colors[`${status}Foreground`] = dark ? '#000000' : '#ffffff';
      }
      colors.destructiveHover = mix(colors.destructive, stateTarget, semantics.hoverMix);
      colors.destructivePressed = mix(colors.destructive, stateTarget, semantics.pressedMix);
      themes[mood][accent] = {
        colors,
        ...staticTokens,
        _meta: { mood, accent, isDark: dark },
      };
    }
  }
  const defaults = themes.dark.violet;
  const css = ['/* Auto-generated by design-tokens build. Do not edit. */', ':root {', '  color-scheme: dark;',
    ...declarations(defaults), '}', ''];
  for (const mood of moodNames) {
    for (const accent of accents) {
      const selectors = [`:root[data-theme="${mood}"][data-accent="${accent}"]`];
      if (accent === 'violet') selectors.push(`:root[data-theme="${mood}"]:not([data-accent])`);
      if (mood === 'dark') selectors.push(`:root:not([data-theme])[data-accent="${accent}"]`);
      css.push(`${selectors.join(',\n')} {`, `  color-scheme: ${mood === 'dark' ? 'dark' : 'light'};`, ...declarations(themes[mood][accent], ['colors']), '}', '');
    }
  }
  const typescript = [
    '// Auto-generated by design-tokens build. Do not edit.',
    `export const VALID_MOODS = ${JSON.stringify(moodNames)} as const;`,
    `export const VALID_ACCENTS = ${JSON.stringify(accents)} as const;`,
    'export type ThemeMood = typeof VALID_MOODS[number];',
    'export type AccentColor = typeof VALID_ACCENTS[number];',
    '',
  ];
  for (const [group, type] of Object.entries({ colors: 'ThemeColors', radii: 'ThemeRadii', spacing: 'ThemeSpacing', typography: 'ThemeTypography', durations: 'ThemeDurations' })) {
    typescript.push(`export interface ${type} {`, ...Object.keys(defaults[group]).map(key => `  readonly ${JSON.stringify(key)}: string;`), '}', '');
  }
  typescript.push(
    'export interface ThemeMeta { readonly mood: ThemeMood; readonly accent: AccentColor; readonly isDark: boolean; }',
    'export interface Theme {',
    '  readonly colors: ThemeColors;',
    '  readonly radii: ThemeRadii;',
    '  readonly spacing: ThemeSpacing;',
    '  readonly typography: ThemeTypography;',
    '  readonly durations: ThemeDurations;',
    '  readonly _meta: ThemeMeta;',
    '}',
    `export const ACCENT_PALETTE: Readonly<Record<AccentColor, string>> = ${JSON.stringify(accentPalette, null, 2)};`,
    'export const ACCENT_OPTIONS = VALID_ACCENTS.map(value => ({ value, hex: ACCENT_PALETTE[value] }));',
    `export const THEMES: Readonly<Record<ThemeMood, Readonly<Record<AccentColor, Theme>>>> = ${JSON.stringify(themes, null, 2)};`,
    `const MOOD_LABELS: Record<ThemeMood, string> = ${JSON.stringify(semantics.moods)};`,
    'export const MOOD_OPTIONS = VALID_MOODS.map(value => ({',
    '  value, label: MOOD_LABELS[value],',
    '  preview: { bg: THEMES[value].violet.colors.background, fg: THEMES[value].violet.colors.foreground, card: THEMES[value].violet.colors.card },',
    '}));',
    '',
  );
  return { themes, css: css.join('\n'), typescript: typescript.join('\n') };
}
